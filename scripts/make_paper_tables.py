#!/usr/bin/env python3
"""Generate markdown tables for the paper from out/report.json.

This script reads a report.json file generated by `python -m vsec run` and emits
Markdown tables suitable for Chapter 7 (Results). It refuses to generate tables
from simulated/synthetic, FAST, or not-citable data unless --allow-draft is given.
A module that was not run (status NA) or is missing from the report produces a
single 'NOT RUN: <reason>' line instead of a table; nothing is ever invented.

Usage:
  python scripts/make_paper_tables.py <report.json> [--allow-draft]

Exit codes:
  0: tables generated
  2: report not citable (simulated/synthetic, FAST, module ERROR, M4 EXPLORATORY) and --allow-draft not given,
     or a module ERROR (never allowed)
  3: cannot load the report (missing, unreadable, not UTF-8 JSON, not an object)
"""
import argparse
import json
import math
import sys

STAMP = "**DRAFT: NOT CITABLE**"


def load_report(path):
    """Load report.json; return the dict or exit 3 with a clear message."""
    try:
        with open(path, encoding="utf-8") as f:
            report = json.load(f)
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as e:  # OSError covers a missing file or a folder
        print(f"error: cannot load {path}: {type(e).__name__}: {e}", file=sys.stderr)
        sys.exit(3)
    if not isinstance(report, dict):
        print(f"error: cannot load {path}: top level is not a JSON object", file=sys.stderr)
        sys.exit(3)
    return report


def _d(x):
    return x if isinstance(x, dict) else {}


def _module(report, prefix):
    """The module dict whose key is `prefix` or starts with it ('M1' -> 'M1 (audit)'); None if absent."""
    for name, mod in _d(report.get("modules")).items():
        if name == prefix or name.startswith(prefix + " "):
            return _d(mod)
    return None


def check_citable(report, allow_draft):
    """Refuse (return False) if the report is not citable. A module ERROR is never allowed."""
    if report.get("modules_failed"):
        print("error: one or more modules failed (ERROR status); results incomplete", file=sys.stderr)
        return False
    if allow_draft:
        return True
    if report.get("contains_simulated_or_synthetic"):
        print("error: report contains simulated or synthetic data; use --allow-draft to generate draft tables", file=sys.stderr)
        return False
    if report.get("fast"):
        print("error: report is from FAST mode (reduced bootstrap); not citable; use --allow-draft for draft tables", file=sys.stderr)
        return False
    m4 = _module(report, "M4") or {}
    if m4.get("status") == "EXPLORATORY" or m4.get("citable") is False:
        print("error: M4 results are EXPLORATORY / not citable (not exactly 15 sessions per class, or simulated); "
              "use --allow-draft for draft tables", file=sys.stderr)
        return False
    return True


# ---- cell formatting: a missing value is "n/a", never the text None or nan ----

def _n(v, nd=3):
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float) and math.isfinite(v):
        return f"{v:.{nd}f}"
    return "n/a"


def _ci(ci, nd=3):
    if isinstance(ci, (list, tuple)) and len(ci) == 2:
        return f"[{_n(ci[0], nd)}, {_n(ci[1], nd)}]"
    return "n/a"


def _s(v):
    """Text cell: empty/None -> n/a; pipes escaped so a value cannot break the table."""
    if v is None or v == "":
        return "n/a"
    return str(v).replace("|", "\\|").replace("\n", " ")


def _table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return lines


def _not_run(reason):
    return [f"NOT RUN: {_s(reason)}"]


def _module_or_not_run(report, prefix):
    """(module, None) when it has data, else (None, ['NOT RUN: ...'])."""
    mod = _module(report, prefix)
    if mod is None:
        return None, _not_run(f"module {prefix} is not in the report")
    if mod.get("status") == "NA":
        return None, _not_run(mod.get("reason") or "module status is NA")
    if mod.get("status") == "ERROR":
        return None, _not_run(f"module errored: {mod.get('reason') or 'no reason given'}")
    return mod, None


# ---- section builders: each returns a list of blocks; a block is table lines or a plain line ----

def threat_class_matrix(report):
    classes = _d(_d(report.get("matrix")).get("classes"))
    if not classes:
        return [_not_run("no threat-class matrix in the report")]
    rows = [[_s(name), _s(c.get("label")), _s(c.get("effective_label")), _n(c.get("controls")), _n(c.get("tested")),
             _n(c.get("na"))] for name, c in classes.items() for c in [_d(c)]]
    return [_table(["Threat class", "Label", "Effective label (this run)", "Controls", "Tested", "N/A"], rows)]


def per_vm_matrix(report):
    matrix = _d(report.get("matrix"))
    vms, classes = _d(matrix.get("vms")), list(_d(matrix.get("classes")))
    if not vms or not classes:
        return [_not_run("no per-VM matrix in the report")]
    rows = []
    for vm, per_class in vms.items():
        cells = []
        for c in classes:
            d = _d(_d(per_class).get(c))
            cells.append(f"{_s(d.get('status'))} ({_n(d.get('tested'))}/{_n(d.get('controls'))})" if d else "--")
        rows.append([_s(vm)] + cells)
    return [_table(["VM"] + [_s(c) for c in classes], rows)]


def m1_results(report):
    m1, err = _module_or_not_run(report, "M1")
    if err:
        return [err]
    ev = _d(m1.get("evaluation_synthetic"))
    overall = _d(ev.get("overall"))
    if not overall:
        return [_not_run("M1 has no evaluation_synthetic.overall in the report")]
    rows = [["Precision", _n(overall.get("precision")), _ci(overall.get("precision_ci"))],
            ["Recall", _n(overall.get("recall")), _ci(overall.get("recall_ci"))],
            ["F1", _n(overall.get("f1")), "n/a"],
            ["False positive rate", _n(overall.get("fpr")), _ci(overall.get("fpr_ci"))]]
    counts = (f"Counts over {_n(m1.get('cases'))} cases ({m1.get('kind', 'n/a')}): TP {_n(overall.get('tp'))}, "
              f"FP {_n(overall.get('fp'))}, FN {_n(overall.get('fn'))}, TN {_n(overall.get('tn'))}. "
              "These are self-consistency results, not independent ground truth.")
    blocks = [_table(["Metric", "Value", "95% CI"], rows), [counts]]
    per_control = _d(ev.get("per_control"))
    if per_control:
        crow = [[_s(c), _n(v.get("tp")), _n(v.get("fp")), _n(v.get("fn")), _n(v.get("tn")), _n(v.get("precision")),
                 _n(v.get("recall"))] for c, v in per_control.items() for v in [_d(v)]]
        blocks.append(_table(["Control", "TP", "FP", "FN", "TN", "Precision", "Recall"], crow))
    return blocks


def m2_results(report):
    m2, err = _module_or_not_run(report, "M2")
    if err:
        return [err]
    cells = _d(m2.get("cells"))
    if not cells:
        return [_not_run("M2 has no cells in the report")]
    rows = [[_s(name), _n(c.get("detected")), _n(c.get("present")), _n(c.get("recall")), _ci(c.get("ci"))]
            for name, c in cells.items() for c in [_d(c)]]
    blocks = [_table(["Secret type / state [/ encoding]", "Detected", "Present", "Recall", "95% CI"], rows)]
    groups = [[g, _n(_d(m2.get(g)).get("detected")), _n(_d(m2.get(g)).get("present")),
               _n(_d(m2.get(g)).get("recall")), _ci(_d(m2.get(g)).get("ci"))]
              for g in ("plain", "held_out", "real_programs") if g in m2]
    if groups:
        blocks.append(_table(["Group", "Detected", "Present", "Recall", "95% CI"], groups))
    blocks.append([f"Scan: {_n(m2.get('dumps'))} dumps, {_n(m2.get('gb_scanned'), 4)} GB, "
                   f"{_n(m2.get('total_hits'))} hits, {_n(m2.get('false_positives'))} false positives "
                   f"({_n(m2.get('fp_per_gb'))} per GB). Dumps synthetic: {_n(m2.get('synthetic'))}."])
    return blocks


def m3_results(report):
    m3, err = _module_or_not_run(report, "M3")
    if err:
        return [err]
    if "hidden_total" not in m3:
        return [_not_run("M3 has no detection counts in the report")]
    rows = [["Hidden objects detected", f"{_n(m3.get('detected'))} / {_n(m3.get('hidden_total'))}",
             _ci(m3.get("detection_ci"))],
            ["Clean dumps with a false alarm", f"{_n(m3.get('clean_with_alarm'))} / {_n(m3.get('clean_dumps'))}",
             _ci(m3.get("clean_alarm_ci"))],
            ["Extra items reported (not hidden)", _n(m3.get("false_items")), "n/a"]]
    blocks = [_table(["Measure", "Count", "95% CI"], rows)]
    failures = m3.get("failures")
    blocks.append([f"Images with a missed hidden object: {', '.join(map(str, failures)) if failures else 'none'}."])
    return blocks


def m4_summary(m4):
    sessions = _d(m4.get("n_sessions"))
    rows = [["Status", _s(m4.get("status"))], ["Citable", _n(m4.get("citable"))],
            ["Why exploratory", _s("; ".join(map(str, m4.get("exploratory_reasons") or [])))],
            ["Classifier family", _s(m4.get("primary_family"))], ["T_short (s)", _n(m4.get("t_short_s"), 2)],
            ["Sessions per class", _s(", ".join(f"{k}: {v}" for k, v in sessions.items()))]]
    return _table(["Item", "Value"], rows)


def m4_hypotheses(m4):
    h1, h2, h3, h4 = (_d(m4.get(h)) for h in ("H1", "H2", "H3", "H4"))
    rows = [
        ["H1 combined vs best single signal (AUROC)", f"single {_n(h1.get('auroc_single'))}, "
         f"combined {_n(h1.get('auroc_combined'))}", f"diff {_n(h1.get('diff'))} {_ci(h1.get('ci'))}",
         _n(h1.get("p_one_sided"), 4), _s(h1.get("status")) if h1.get("supported") is None else _n(h1.get("supported"))],
        ["H2 FPR at TPR 0.90", f"single {_n(h2.get('fpr_single'))}, combined {_n(h2.get('fpr_combined'))}",
         f"diff {_ci(h2.get('diff_single_minus_combined_ci'))}", _n(h2.get("p"), 4), _n(h2.get("supported"))],
        ["H3 held-out workload (AUROC)", f"in-dist {_n(h3.get('auroc_in_distribution'))}, "
         f"held-out {_n(h3.get('auroc_held_workload'))}", f"drop {_n(h3.get('auroc_drop'))} {_ci(h3.get('drop_ci'))}",
         _n(h3.get("p"), 4), _n(h3.get("supported"))],
        ["H4 practical cost", f"{_n(h4.get('seconds'), 2)} s, CPU {_n(h4.get('cpu_percent'), 2)} %",
         f"time {_ci(h4.get('seconds_ci'), 2)} s", "n/a", _n(h4.get("supported"))],
    ]
    blocks = [_table(["Hypothesis", "Result", "Difference / interval", "p", "Supported"], rows)]
    if h1.get("reason"):
        blocks.append([f"H1: {_s(h1['reason'])}"])
    return blocks


def m4_curve(m4):
    curve = _d(_d(m4.get("curve")).get("logreg"))
    ts = curve.get("t") or []
    if not ts:
        return None

    def at(key, i):
        vals = curve.get(key)
        return _n(vals[i]) if isinstance(vals, list) and i < len(vals) else "n/a"
    rows = [[_n(t, 1), at("single_auroc", i), at("combined_auroc", i), at("cost_s", i)] for i, t in enumerate(ts)]
    return _table(["T (s)", "Single AUROC", "Combined AUROC", "Decision cost (s)"], rows)


def m4_balance_confounds(m4):
    blocks = []
    balance = _d(m4.get("balance"))
    if balance:
        rows = [[_s(k), _n(v.get("imbalanced")), _s("; ".join(f"{p}: {_n(s, 2)}" for p, s in _d(v.get("smd")).items()))]
                for k, v in balance.items() for v in [_d(v)]]
        blocks.append(_table(["Covariate", "Imbalanced", "Standardised mean difference"], rows))
    confounds = _d(m4.get("confounds"))
    rows = [[_s(k), _n(v.get("differs")), _s("; ".join(f"{c}: {','.join(map(str, vals))}"
                                                        for c, vals in _d(v.get("values")).items()))]
            for k, v in confounds.items() if "values" in _d(v) for v in [_d(v)]]
    if rows:
        blocks.append(_table(["Setup field", "Differs across classes", "Values per class"], rows))
    return blocks


def indicator_leak_table(m4):
    leaks = m4.get("indicator_leaks")
    if not isinstance(leaks, list) or not leaks:
        return _not_run("no indicator values were recorded in the sessions")
    rows = [[_s(r.get("indicator")), _s(", ".join(map(str, r.get("native") or []))),
             _s(", ".join(map(str, r.get("kvm-plain") or []))), _s(", ".join(map(str, r.get("kvm-masked") or []))),
             "unknown" if r.get("masked_leaks") is None else _n(r.get("masked_leaks"))] for r in leaks if isinstance(r, dict)]
    return _table(["Indicator", "native", "kvm-plain", "kvm-masked", "Masked value leaks"], rows)


def m4_sections(report):
    """[(heading, blocks)] for M4; a single NOT RUN line when M4 has no data."""
    m4, err = _module_or_not_run(report, "M4")
    if err:
        return [("## M4 Hypervisor Detection", [err])]
    sections = [("## M4 Hypervisor Detection", [m4_summary(m4)]),
                ("### M4 Hypotheses H1 to H4", m4_hypotheses(m4)),
                ("### M4 Detection Time Curve", [m4_curve(m4) or _not_run("no curve in the report")]),
                ("### M4 Session Balance and Setup Confounds",
                 m4_balance_confounds(m4) or [_not_run("no balance data in the report")]),
                ("### M4 Indicator Leaks", [indicator_leak_table(m4)])]
    return sections


def build_sections(report):
    return ([("## Threat Class Result Matrix", threat_class_matrix(report)),
             ("## Per-VM Status", per_vm_matrix(report)),
             ("## M1 Configuration Auditor", m1_results(report)),
             ("## M2 Snapshot Privacy", m2_results(report)),
             ("## M3 Memory Forensics", m3_results(report))] + m4_sections(report))


def render(report, allow_draft):
    """The whole markdown document. The draft stamp is its own line above every table."""
    out = []
    for heading, blocks in build_sections(report):
        out += ["", heading, ""]
        for block in blocks:
            is_table = bool(block) and block[0].startswith("|")
            if is_table and allow_draft:
                out += [STAMP, ""]
            out += block + [""]
    if allow_draft:
        out += ["---", "", f"{STAMP}: generated with --allow-draft. Data is simulated, synthetic or exploratory."]
    return "\n".join(out).strip("\n") + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Generate Markdown tables for the paper from a report.json file.")
    parser.add_argument("report", help="Path to report.json")
    parser.add_argument("--allow-draft", action="store_true",
                        help="Allow draft output from simulated/synthetic data (stamps each table 'DRAFT: NOT CITABLE')")
    args = parser.parse_args(argv)

    report = load_report(args.report)
    if not check_citable(report, args.allow_draft):
        return 2
    sys.stdout.write(render(report, args.allow_draft))
    return 0


if __name__ == "__main__":
    sys.exit(main())
